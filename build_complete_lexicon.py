# Translate any token or phrase
def translate_phrase(text):
    text_clean = text.strip()
    if not text_clean:
        return {"hi": "", "kn": "", "ta": "", "te": "", "ml": ""}
    
    # Direct match in WORD_MAP
    lower = text_clean.lower()
    if lower in WORD_MAP:
        v = WORD_MAP[lower]
        return {"hi": v[0], "kn": v[1], "ta": v[2], "te": v[3], "ml": v[4]}

    # Punctuation / symbol / quote wrappers
    m_sym = re.match(r'^([•✓✕→←★*!+—–\-\s]*)(.+?)([:.?!,;—–\-\s]*)$', text_clean)
    if m_sym and (m_sym.group(1) or m_sym.group(3)):
        prefix = m_sym.group(1)
        core = m_sym.group(2)
        suffix = m_sym.group(3)
        if core != text_clean:
            t_core = translate_phrase(core)
            return {
                "hi": f"{prefix}{t_core['hi']}{suffix}",
                "kn": f"{prefix}{t_core['kn']}{suffix}",
                "ta": f"{prefix}{t_core['ta']}{suffix}",
                "te": f"{prefix}{t_core['te']}{suffix}",
                "ml": f"{prefix}{t_core['ml']}{suffix}"
            }

    # Parentheses or brackets
    m_brack = re.match(r'^([\(\[\{])(.+)([\)\]\}])$', text_clean)
    if m_brack:
        p_open, inner, p_close = m_brack.group(1), m_brack.group(2), m_brack.group(3)
        t_inner = translate_phrase(inner)
        return {
            "hi": f"{p_open}{t_inner['hi']}{p_close}",
            "kn": f"{p_open}{t_inner['kn']}{p_close}",
            "ta": f"{p_open}{t_inner['ta']}{p_close}",
            "te": f"{p_open}{t_inner['te']}{p_close}",
            "ml": f"{p_open}{t_inner['ml']}{p_close}"
        }

    # Number + unit: e.g. "10 yrs", "14 Days", "3 minutes"
    m_num_unit = re.match(r'^(\d+[\.\d]*)\s*([a-zA-Z\s]+)$', text_clean)
    if m_num_unit:
        num = m_num_unit.group(1)
        u_str = m_num_unit.group(2).strip().lower()
        if u_str in WORD_MAP:
            u_trans = WORD_MAP[u_str]
            return {
                "hi": f"{num} {u_trans[0]}",
                "kn": f"{num} {u_trans[1]}",
                "ta": f"{num} {u_trans[2]}",
                "te": f"{num} {u_trans[3]}",
                "ml": f"{num} {u_trans[4]}"
            }

    # Colon separator: e.g. "Status: Completed", "Age: 58"
    if ': ' in text_clean:
        parts = text_clean.split(': ', 1)
        t1 = translate_phrase(parts[0])
        t2 = translate_phrase(parts[1])
        return {
            "hi": f"{t1['hi']}: {t2['hi']}",
            "kn": f"{t1['kn']}: {t2['kn']}",
            "ta": f"{t1['ta']}: {t2['ta']}",
            "te": f"{t1['te']}: {t2['te']}",
            "ml": f"{t1['ml']}: {t2['ml']}"
        }

    # Bullet / dash separator: e.g. "Part 1 • Part 2"
    for sep in [' • ', ' — ', ' – ', ' | ']:
        if sep in text_clean:
            parts = text_clean.split(sep)
            t_parts = [translate_phrase(p) for p in parts]
            return {
                "hi": sep.join(p['hi'] for p in t_parts),
                "kn": sep.join(p['kn'] for p in t_parts),
                "ta": sep.join(p['ta'] for p in t_parts),
                "te": sep.join(p['te'] for p in t_parts),
                "ml": sep.join(p['ml'] for p in t_parts)
            }

    # Token-level replacement for multi-word phrases
    tokens = re.split(r'(\s+|[,;.?!:]+)', text_clean)
    hi_tok, kn_tok, ta_tok, te_tok, ml_tok = [], [], [], [], []
    for tok in tokens:
        tok_clean = tok.strip().lower()
        if tok_clean in WORD_MAP:
            t = WORD_MAP[tok_clean]
            # Match capitalization
            if tok.strip().istitle():
                hi_tok.append(t[0])
                kn_tok.append(t[1])
                ta_tok.append(t[2])
                te_tok.append(t[3])
                ml_tok.append(t[4])
            else:
                hi_tok.append(t[0])
                kn_tok.append(t[1])
